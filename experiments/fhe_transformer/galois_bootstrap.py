    def restrict(
        self,
        sn_character: np.ndarray,  # Character of S_n (values on conjugacy classes)
        cyclic_subgroup: CyclicSubgroup
    ) -> np.ndarray:
        """
        Restriction functor: Res^{S_n}_{C_k}

        Takes S_n character ψ and restricts to C_k ⊂ S_n.

        Formula:
            (Res ψ)(g^j) = ψ(g^j)   for g^j ∈ C_k

        where we view g^j as an element of S_n (via the embedding).

        Args:
            sn_character: Character values on S_n conjugacy classes
            cyclic_subgroup: Which C_k to restrict to

        Returns:
            Character values on C_k elements [χ(e), χ(g), χ(g²), ..., χ(g^{k-1})]
        """
        k = cyclic_subgroup.k

        # Get cycle types of C_k elements in S_n
        ck_cycle_types = cyclic_subgroup.elements_as_cycle_types()

        # Restrict by evaluating S_n character on these cycle types
        restricted_values = np.zeros(k, dtype=complex)

