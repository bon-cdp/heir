class CyclicSubgroup:
    """
    Cyclic subgroup of S_n generated by a k-cycle.

    Example:
        In S_5, the element (1 2 3) generates C_3 ⊂ S_5
    """

    def __init__(self, cycle_length: int, embedding_in_Sn: int):
        """
        Args:
            cycle_length: Order of cyclic group (k for C_k)
            embedding_in_Sn: Which S_n this is embedded in
        """
        self.k = cycle_length
        self.n = embedding_in_Sn

        # The cyclic group character theory (we already have this!)
        self.characters = CyclicGroupCharacters(self.k)

    def generator_as_cycle_type(self) -> Partition:
        """
        The k-cycle generator has cycle type [k, 1, 1, ..., 1].

        Example: (1 2 3) in S_5 has cycle type [3, 1, 1]
        """
        parts = [self.k] + [1] * (self.n - self.k)
        return Partition(parts)

    def elements_as_cycle_types(self) -> List[Partition]:
        """
        All elements of C_k as cycle types in S_n.

        Element g^j in C_k corresponds to:
        - j applications of the k-cycle
        - Creates gcd(k, j) cycles of length k/gcd(k,j)
        """
        cycle_types = []

        for j in range(self.k):
            if j == 0:
                # Identity: all 1-cycles
                cycle_types.append(Partition([1] * self.n))
            else:
                # g^j: compute cycle structure
                from math import gcd
                g = gcd(self.k, j)
                num_cycles = g
                cycle_len = self.k // g

                parts = [cycle_len] * num_cycles + [1] * (self.n - self.k)
                cycle_types.append(Partition(parts))

        return cycle_types


class GaloisConnection:
    """
    The adjunction between Restriction and Induction.

    This is the categorical heart of the bootstrap from C_n to S_n.

    Functors:
        F = Res: Rep(S_n) → Rep(C_k)  (restriction - going down)
        G = Ind: Rep(C_k) → Rep(S_n)  (induction - going up)

    Adjunction:
        Hom(G(V), W) ≅ Hom(V, F(W))

    At character level (using inner product):
        ⟨Ind(χ), ψ⟩_{S_n} = ⟨χ, Res(ψ)⟩_{C_k}

    This is what makes the bootstrap work!
    """

